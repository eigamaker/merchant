import fs from "node:fs";
import path from "node:path";

export const ACTOR_SETTINGS_FILE = path.resolve("assets-src/actors/actor-settings.json");
export const ACTOR_SETTINGS_GENERATED_TS = path.resolve("src/game/actorSettings.generated.ts");

/** Mirrors ActorRole in src/game/actorSettings.ts. */
const roles = new Set(["player", "npc", "enemy", "townsfolk", "adventurer"]);
/** Identity, not numbers. The curve lives in src/game/dungeonDifficulty.ts. */
const archetypes = new Set(["brute", "swarm", "caster", "lurker"]);
const MAX_TIER = 5;

export function normalizeActorSettings(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("actor settings must be an object");
  const raw = value;
  if (raw.version !== 1) throw new Error("actor settings version must be 1");
  if (!raw.actors || typeof raw.actors !== "object" || Array.isArray(raw.actors)) throw new Error("actor settings actors must be an object");
  const actors = {};
  for (const [id, rawSettings] of Object.entries(raw.actors)) {
    if (!/^[a-z][a-z0-9._-]*$/.test(id)) throw new Error(`invalid actor settings id: ${id}`);
    if (!rawSettings || typeof rawSettings !== "object" || Array.isArray(rawSettings)) throw new Error(`invalid actor settings: ${id}`);
    const settings = rawSettings;
    const normalized = {};
    if (settings.label !== undefined) {
      if (typeof settings.label !== "string" || settings.label.trim().length === 0 || settings.label.length > 200) throw new Error(`invalid actor label: ${id}`);
      normalized.label = settings.label.trim();
    }
    if (settings.roles !== undefined) {
      if (!Array.isArray(settings.roles) || settings.roles.some((role) => !roles.has(role))) throw new Error(`invalid actor roles: ${id}`);
      normalized.roles = [...new Set(settings.roles)];
    }
    if (settings.archetype !== undefined) {
      if (!archetypes.has(settings.archetype)) throw new Error(`invalid actor archetype: ${id}`);
      normalized.archetype = settings.archetype;
    }
    if (settings.tier !== undefined) {
      const tier = Number(settings.tier);
      if (!Number.isInteger(tier) || tier < 1 || tier > MAX_TIER) throw new Error(`invalid actor tier: ${id}`);
      normalized.tier = tier;
    }
    if (settings.enemyStats !== undefined) {
      const stats = settings.enemyStats;
      if (!stats || typeof stats !== "object") throw new Error(`invalid enemy stats: ${id}`);
      const values = { baseHp: Number(stats.baseHp), hpPerFloor: Number(stats.hpPerFloor), damage: Number(stats.damage) };
      if (!Number.isFinite(values.baseHp) || values.baseHp < 1 || !Number.isFinite(values.hpPerFloor) || values.hpPerFloor < 0 || !Number.isFinite(values.damage) || values.damage < 0) throw new Error(`invalid enemy stats: ${id}`);
      normalized.enemyStats = values;
    }
    if (settings.scale !== undefined) {
      normalized.scale = Number(settings.scale);
      if (!Number.isFinite(normalized.scale) || normalized.scale <= 0 || normalized.scale > 10) throw new Error(`invalid actor scale: ${id}`);
    }
    if (settings.originY !== undefined) {
      normalized.originY = Number(settings.originY);
      if (!Number.isFinite(normalized.originY) || normalized.originY < 0 || normalized.originY > 1) throw new Error(`invalid actor origin: ${id}`);
    }
    actors[id] = normalized;
  }
  return { version: 1, actors };
}

export function readActorSettings(file = ACTOR_SETTINGS_FILE) {
  if (!fs.existsSync(file)) return { version: 1, actors: {} };
  return normalizeActorSettings(JSON.parse(fs.readFileSync(file, "utf8")));
}

export function writeActorSettingsAtomically(value, { file = ACTOR_SETTINGS_FILE } = {}) {
  const normalized = normalizeActorSettings(value);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(temporary, JSON.stringify(normalized, null, 2) + "\n", "utf8");
  try {
    fs.renameSync(temporary, file);
  } catch (error) {
    fs.rmSync(temporary, { force: true });
    throw error;
  }
  return normalized;
}

export function writeActorSettingsGenerated(file = ACTOR_SETTINGS_GENERATED_TS, settings = readActorSettings()) {
  const normalized = normalizeActorSettings(settings);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const text = `/* AUTO-GENERATED by scripts/build-actor-assets.mjs. Do not edit. */\nimport type { ActorSettingsCatalog } from "./actorSettings";\nexport const GENERATED_ACTOR_SETTINGS: ActorSettingsCatalog = ${JSON.stringify(normalized, null, 2)};\n`;
  fs.writeFileSync(file, text, "utf8");
  return normalized;
}
