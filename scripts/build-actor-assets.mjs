import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ACTOR_SOURCE_DIR = path.resolve("assets-src/actors/imported");
export const ACTOR_OUTPUT_DIR = path.resolve("public/assets/actors/generated");
export const ACTOR_GENERATED_TS = path.resolve("src/game/actorAssetCatalog.generated.ts");

function readDefinitions(sourceDir = ACTOR_SOURCE_DIR) {
  if (!fs.existsSync(sourceDir)) return [];
  const result = [];
  const visit = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) visit(absolute);
      else if (entry.name === "actor.json") result.push({ file: absolute, root: path.dirname(absolute), definition: JSON.parse(fs.readFileSync(absolute, "utf8")) });
    }
  };
  visit(sourceDir);
  return result;
}

function writeGenerated(file, definitions) {
  const text = `/* AUTO-GENERATED by scripts/build-actor-assets.mjs. Do not edit. */\nimport type { CraftpixActorDefinition } from "./craftpixActors";\nexport const GENERATED_ACTORS: readonly CraftpixActorDefinition[] = ${JSON.stringify(definitions, null, 2)};\n`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, "utf8");
}

export function buildActorAssets({ sourceDir = ACTOR_SOURCE_DIR, outputDir = ACTOR_OUTPUT_DIR, generatedTs = ACTOR_GENERATED_TS } = {}) {
  const records = readDefinitions(sourceDir);
  fs.mkdirSync(outputDir, { recursive: true });
  for (const entry of fs.readdirSync(outputDir)) fs.rmSync(path.join(outputDir, entry), { recursive: true, force: true });
  const definitions = [];
  for (const { root, definition } of records) {
    if (!definition || typeof definition.id !== "string" || !definition.id) throw new Error("actor definition id is required");
    const clips = {};
    for (const [action, clip] of Object.entries(definition.clips ?? {})) {
      if (!clip || typeof clip.path !== "string") continue;
      const source = path.resolve("assets-src/actors", clip.path);
      if (!source.startsWith(path.resolve("assets-src/actors") + path.sep) || !fs.existsSync(source)) throw new Error(`missing actor clip: ${clip.path}`);
      const target = path.join(outputDir, definition.id, `${action}.png`);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(source, target);
      clips[action] = { ...clip, path: `/assets/actors/generated/${definition.id}/${action}.png` };
    }
    definitions.push({ ...definition, clips });
  }
  definitions.sort((a, b) => a.id.localeCompare(b.id));
  writeGenerated(generatedTs, definitions);
  fs.writeFileSync(path.join(outputDir, "catalog.json"), JSON.stringify({ version: 1, actors: definitions }, null, 2) + "\n", "utf8");
  return definitions;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = buildActorAssets();
  console.log(`Generated ${result.length} imported actor definitions.`);
}
